    <h1>Conditions générales de vente</h1>

    <h2>1. Commande</h2>
    <p>Les commandes sont passées en ligne depuis un compte client. Chaque menu est commandé pour un nombre de personnes
        au moins égal au minimum indiqué sur sa fiche. Les conditions propres à chaque menu (délai de commande, conservation)
        sont affichées sur la fiche du menu et doivent être respectées.</p>

    <h2>2. Prix</h2>
    <p>Les prix sont indiqués en euros TTC. Une réduction de 10 % est appliquée sur le prix du menu dès que la commande
        compte au moins 5 personnes de plus que le minimum du menu.</p>

    <h2>3. Livraison</h2>
    <p>La livraison est offerte dans la ville de Bordeaux. Hors Bordeaux, elle est facturée 5 € plus 0,59 € par kilomètre
        entre Bordeaux et le lieu de la prestation.</p>

    <h2>4. Modification et annulation</h2>
    <p>Le client peut modifier (sauf le choix du menu) ou annuler sa commande depuis son espace tant qu'elle n'a pas été
        acceptée par notre équipe. Au-delà, toute demande se fait en nous contactant.</p>

    <h2>5. Prêt de matériel</h2>
    <p>Le matériel prêté (vaisselle, réchauds...) doit être restitué <strong>sous 10 jours ouvrés</strong> après la livraison.
        À défaut, des frais de <strong>600 €</strong> seront facturés au client. Pour organiser la restitution, le client prend contact avec la société.</p>

    <h2>6. Allergènes</h2>
    <p>Les allergènes de chaque plat sont indiqués sur la fiche du menu. Il appartient au client de vérifier leur compatibilité
        avec les convives.</p>

    <h2>7. Avis clients</h2>
    <p>Une fois la commande terminée, le client peut laisser une note et un commentaire. Les avis sont publiés après modération.</p>
